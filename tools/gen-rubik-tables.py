#!/usr/bin/env python3
"""Generate the small IDA* abstractions, never a full-cube solution table.

Usage: python3 tools/gen-rubik-tables.py | clang-format-20 > \
           src/rubik/rubik_tables.h
       python3 tools/gen-rubik-tables.py --assembly > \
           src/rubik/rubik_asm_tables.S
The rank order and nibble layout match gy0719/minirubik my_solver.c and
solver_tables.S. Only this offline generator uses queues.
"""

import argparse
from collections import deque
from itertools import permutations, product


SOURCE = ((1, 4, 2, 0, 3, 5, 6), (0, 1, 2, 4, 5, 6, 3),
          (0, 2, 5, 3, 1, 4, 6))
TWIST = ((1, 2, 0, 2, 1, 0, 0), (0, 0, 0, 1, 2, 1, 2),
         (0, 0, 0, 0, 0, 0, 0))


def transitions(states, orientation=False):
    ranks = {state: rank for rank, state in enumerate(states)}
    return [[ranks[tuple((state[src] + TWIST[face][i]) % 3
                        if orientation else state[src]
                        for i, src in enumerate(source))]
             for state in states] for face, source in enumerate(SOURCE)]


def distances(rows):
    distance = [255] * len(rows[0])
    distance[0] = 0
    queue = deque([0])
    while queue:
        here = queue.popleft()
        for row in rows:
            there = here
            for _ in range(3):
                there = row[there]
                if distance[there] == 255:
                    distance[there] = distance[here] + 1
                    queue.append(there)
    assert max(distance) < 16
    return [distance[i] | (distance[i + 1] << 4
                          if i + 1 < len(distance) else 0)
            for i in range(0, len(distance), 2)]


def emit(name, rows, bits, matrix=False):
    width = len(rows[0])
    shape = f"[3][{width}]" if matrix else f"[{width}]"
    print(f"static const uint{bits}_t {name}{shape} = {{")
    for row in rows:
        if matrix:
            print("    {")
        for start in range(0, len(row), 8):
            print("        " + ", ".join(f"0x{v:0{bits // 4}x}"
                                        for v in row[start:start + 8]) + ",")
        if matrix:
            print("    },")
    print("};\n")


def emit_assembly(name, rows, bits):
    name = "rubik_asm_" + name
    print(f"    .balign {bits // 8}\n    .globl {name}")
    print(f"    .hidden {name}\n    .type {name}, @object\n{name}:")
    directive = ".half" if bits == 16 else ".byte"
    for row in rows:
        for start in range(0, len(row), 8):
            print(f"    {directive} " + ", ".join(
                f"0x{v:0{bits // 4}x}" for v in row[start:start + 8]))
    print(f"    .size {name}, . - {name}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assembly", action="store_true",
                        help="emit self-contained RV32I read-only tables")
    args = parser.parse_args()
    perm = transitions(list(permutations(range(7))))
    ori = transitions([digits + ((-sum(digits)) % 3,)
                       for digits in product(range(3), repeat=6)], True)
    print("/* Generated by tools/gen-rubik-tables.py; do not edit. */")
    if args.assembly:
        print('    .section .rodata,"a",@progbits\n')
        emit_assembly("perm_move_table", perm, 16)
        emit_assembly("ori_move_table", ori, 16)
        emit_assembly("hp_packed", [distances(perm)], 8)
        emit_assembly("ho_packed", [distances(ori)], 8)
        return
    print("#pragma once\n\n#include <stdint.h>\n")
    emit("perm_move_table", perm, 16, True)
    emit("ori_move_table", ori, 16, True)
    emit("hp_packed", [distances(perm)], 8)
    emit("ho_packed", [distances(ori)], 8)


if __name__ == "__main__":
    main()
