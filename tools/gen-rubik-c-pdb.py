#!/usr/bin/env python3
"""Generate subset-corner distances and factored transitions offline.

Usage: python3 tools/gen-rubik-c-pdb.py 4 /tmp/rubik-c-pdb
       clang-format-20 /tmp/rubik-c-pdb/pdb.h > src/rubik/rubik_c_pdb.h

The target contains only abstract tables; the BFS queue is host-only.
"""
from collections import deque
from itertools import permutations, product
from pathlib import Path
import argparse
import json

SOURCE = ((1, 4, 2, 0, 3, 5, 6), (0, 1, 2, 4, 5, 6, 3),
          (0, 2, 5, 3, 1, 4, 6))
TWIST = ((1, 2, 0, 2, 1, 0, 0), (0, 0, 0, 1, 2, 1, 2),
         (0, 0, 0, 0, 0, 0, 0))


def build(k):
    positions = list(permutations(range(7), k))
    position_rank = {state: i for i, state in enumerate(positions)}
    orientations = list(product(range(3), repeat=k))
    orientation_rank = {state: i for i, state in enumerate(orientations)}
    inverse = [[SOURCE[face].index(i) for i in range(7)] for face in range(3)]
    raw = []
    deltas = set()
    for face in range(3):
        row = []
        for pos in positions:
            new = tuple(inverse[face][i] for i in pos)
            delta = tuple(TWIST[face][i] for i in new)
            deltas.add(delta)
            row.append((position_rank[new], delta))
        raw.append(row)
    deltas = sorted(deltas)
    delta_rank = {d: i for i, d in enumerate(deltas)}
    n_ori = len(orientations)
    update = [[orientation_rank[tuple((v + d) % 3 for v, d in zip(ori, delta))]
               for ori in orientations] for delta in deltas]
    update_flat = [value for row in update for value in row]
    transitions = [[((delta_rank[delta] * n_ori) << 17) | (new << 7)
                    for new, delta in row] for row in raw]
    dist = bytearray([255]) * (len(positions) * n_ori)
    dist[0] = 0
    queue = deque([0])
    histogram = [0] * 16
    while queue:
        state = queue.popleft()
        pos, ori = divmod(state, n_ori)
        d = dist[state]
        histogram[d] += 1
        for face in range(3):
            new_pos, new_ori = pos, ori
            for _ in range(3):
                entry = transitions[face][new_pos]
                new_pos = (entry & 0x1ffff) >> 7
                new_ori = update_flat[(entry >> 17) + new_ori]
                child = new_pos * n_ori + new_ori
                if dist[child] == 255:
                    dist[child] = d + 1
                    queue.append(child)
    assert sum(histogram) == len(dist) and max(dist) < 16
    packed = [dist[i] | (dist[i + 1] << 4 if i + 1 < len(dist) else 0)
              for i in range(0, len(dist), 2)]
    perm_map = [position_rank[tuple(p.index(cubie) for cubie in range(k))]
                for p in permutations(range(7))]
    return dict(k=k, positions=len(positions), orientations=n_ori,
                deltas=len(deltas), histogram=histogram,
                transitions=transitions, update=update, packed=packed,
                perm_map=perm_map)


def emit_values(out, name, rows, bits, assembly):
    values = [x for row in rows for x in row]
    if assembly:
        symbol = 'rubik_pdb_' + name
        out.write(f'    .balign {bits // 8}\n    .globl {symbol}\n')
        out.write(f'    .hidden {symbol}\n    .type {symbol}, @object\n{symbol}:\n')
        directive = {8: '.byte', 16: '.half', 32: '.word'}[bits]
        width = 6 if bits == 32 else 8
        for i in range(0, len(values), width):
            out.write(f'    {directive} ' + ', '.join(
                f'0x{v:0{bits // 4}x}' for v in values[i:i + width]) + '\n')
        out.write(f'    .size {symbol}, . - {symbol}\n')
    else:
        out.write(f'static const uint{bits}_t pdb_{name}[{len(values)}] = {{\n')
        for i in range(0, len(values), 12):
            out.write('    ' + ', '.join(str(v) for v in values[i:i + 12]) + ',\n')
        out.write('};\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('k', type=int, choices=(3, 4))
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    data = build(args.k)
    stats = {k: v for k, v in data.items()
             if k in ('k', 'positions', 'orientations', 'deltas', 'histogram')}
    (args.out / 'stats.json').write_text(json.dumps(stats, indent=2) + '\n')
    for suffix, assembly in [('h', False), ('S', True)]:
        with (args.out / f'pdb.{suffix}').open('w') as out:
            if assembly:
                out.write('/* Generated by tools/gen-rubik-pdb.py; do not edit. */\n')
                out.write('    .section .rodata,"a",@progbits\n')
            else:
                out.write('/* Generated by tools/gen-rubik-c-pdb.py; do not edit. */\n')
                out.write('#pragma once\n\n#include <stdint.h>\n')
                out.write(f'#define PDB_ORIENTATIONS {data["orientations"]}\n')
                out.write(f'#define PDB_POSITIONS {data["positions"]}\n')
            for name, rows, bits in [('moves', data['transitions'], 32),
                                      ('orientation', data['update'], 8),
                                      ('distances', [data['packed']], 8),
                                      ('perm_map', [data['perm_map']], 16)]:
                emit_values(out, name, rows, bits, assembly)
    print(json.dumps(stats))


if __name__ == '__main__':
    main()
